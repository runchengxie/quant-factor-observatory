import { test, expect } from '@playwright/test'
test('Alpha catalog paginates all published evidence and resets filtering', async ({ page }) => {
  await page.goto('/alpha810')
  const rows = page.locator('.factor-table tbody tr')
  await expect(rows).toHaveCount(50)
  const first = await rows.first().innerText()
  await page.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(rows).toHaveCount(50)
  expect(await rows.first().innerText()).not.toBe(first)
  await page.getByPlaceholder('alpha101_001').fill('alpha101_001')
  await expect(rows).toHaveCount(1)
  await expect(page.getByRole('button', { name: 'Previous', exact: true })).toBeDisabled()
  await page.getByPlaceholder('alpha101_001').fill('')
  await page.getByRole('button', { name: 'Show all matching factors' }).click()
  await expect(rows).toHaveCount(810)
  await expect(page.getByRole('link', { name: 'Download full snapshot (JSON)' })).toHaveAttribute('href', '/data/alpha810-snapshot.json')
})
test('PB ROE comparison precedes full evidence and preserves all five rows', async ({ page }) => {
  await page.goto('/studies/pb-roe')
  await expect(page.locator('#historical-comparison tbody tr')).toHaveCount(5)
  await expect(page.locator('#comparison-limits')).toContainText('2010-01-29 to 2026-08-31')
  expect(await page.locator('#historical-comparison').evaluate(element => !!(element.compareDocumentPosition(document.querySelector('#full-evidence')!) & Node.DOCUMENT_POSITION_FOLLOWING))).toBe(true)
  await expect(page.locator('#full-evidence .study-trust-card')).toBeVisible()
})
