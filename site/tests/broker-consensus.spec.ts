import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.context().route('https://fonts.googleapis.com/**', route => route.fulfill({ contentType: 'text/css', body: '' }))
  await page.addInitScript(() => window.localStorage.setItem('quant-factor-locale', 'en-US'))
})

test('broker study unfolds every chart and exact table without a dropdown', async ({ page }) => {
  await page.goto('/studies/broker-consensus')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Can broker earnings forecasts help rank stocks?')
  const charts = page.locator('.study-expanded-chart')
  await expect(charts).toHaveCount(25)
  await expect(page.locator('.study-exploration-select')).toHaveCount(0)
  await expect(page.locator('.study-expanded-reader details')).toHaveCount(0)
  const identities = await charts.evaluateAll(elements => elements.map(element => element.id))
  expect(new Set(identities).size).toBe(25)
  for (const id of identities) {
    const chart = page.locator(`#${id}`)
    await expect(chart.locator('.study-exploration-svg')).toBeVisible()
    await expect(chart.locator('.study-values')).toBeVisible()
    await expect(chart.locator('.study-values tbody tr')).not.toHaveCount(0)
  }
  const matched = page.locator('#study-chart-matched-timing-ranks')
  await expect(matched).toContainText('52 months')
  await expect(matched.locator('.study-uncertainty').first()).toBeVisible()
  await expect(matched.locator('.study-chart-context')).toContainText('Identical stocks')
  await expect(page.locator('.study-trust-card')).toContainText('Original provider vintages remain unknown')
  await expect(page.locator('.study-reproduction')).toContainText('fe38eba06e56fb2947b947667511cdf951e5f397')
  await expect(page.locator('#study-chart-paired-valuation-rankic')).toContainText('removing its relationship with the reported earnings yield ranking')
  await expect(page.locator('#study-chart-forecast-reported-rankic-delta')).toContainText('For each common month, calculate RankIC')
  await expect(page.locator('#study-chart-missing-endpoint-reasons')).toContainText('11,498 missing endpoints')
  await matched.screenshot({ path: test.info().outputPath('broker-expanded-intervals.png') })
})

