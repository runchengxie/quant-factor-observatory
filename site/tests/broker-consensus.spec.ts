test('reader anchors jump to expanded charts and legends operate independently', async ({ page }) => {
  await page.goto('/studies/broker-consensus')
  await expect(page.locator('.detail-head .lede')).toContainText('insufficient to use broker consensus as a reliable standalone stock-selection factor')
  await expect(page.locator('.study-reader-block')).toHaveCount(6)
  await page.locator('#reader-profit').getByRole('link', { name: /View chart · Profitable companies: do forecasts beat/ }).click()
  await expect(page).toHaveURL(/#study-chart-benchmark-profit$/)
  const profit = page.locator('#study-chart-benchmark-profit')
  await expect(profit).toBeInViewport()
  await expect(profit.locator('rect')).toHaveCount(6)
  await profit.getByRole('button', { name: 'Broker forecast', exact: true }).click()
  await expect(profit.getByRole('button', { name: 'Broker forecast', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await expect(profit.locator('rect')).toHaveCount(3)
  await expect(profit.locator('.study-values')).toContainText('13.48%')
  await expect(profit.locator('.study-values thead th')).toHaveCount(3)
  await expect(page.locator('#study-chart-benchmark-loss rect')).toHaveCount(6)
  const paired = page.locator('#study-chart-benchmark-paired-improvement')
  await expect(paired.locator('.study-values')).toContainText('95% interval')
  await expect(paired.locator('.study-values')).not.toContainText('11 months')
  await expect(page.locator('#reader-loss').getByRole('link', { name: /View chart · Does the paired/ })).toHaveAttribute('href', '#study-chart-benchmark-paired-improvement')
  await page.getByRole('button', { name: 'Switch to 中文' }).click()
  await expect(page.locator('.detail-head .lede')).toContainText('目前证据还不足以把券商一致预期当作可靠、可直接使用的选股因子')
  await expect(page.locator('#reader-selection')).toContainText('预测利润更准，也不能保证买股票多赚钱')
  await page.locator('#reader-profit').scrollIntoViewIfNeeded()
  await page.screenshot({ path: test.info().outputPath('broker-expanded-desktop.png') })
})

test('malformed reader chart links preserve the study and offer a retry', async ({ page }) => {
  await page.route('**/data/study-exploration/broker-consensus.json', async route => {
    const data = await (await route.fetch()).json()
    data.reader.sections[0].chart_ids = ['missing-evidence']
    await route.fulfill({ json: data })
  })
  await page.goto('/studies/broker-consensus')
  await expect(page.locator('h1')).toHaveText('Can broker earnings forecasts help rank stocks?')
  await expect(page.getByRole('button', { name: 'Retry' }).last()).toBeVisible()
})
